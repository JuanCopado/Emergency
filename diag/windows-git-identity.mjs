// Diagnostic only (throwaway). Linked worktree on Windows: why is status dirty right after `worktree add`?
import { spawnSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const gitExe = 'C:\\Program Files\\Git\\cmd\\git.exe';
const env = { PATH: '', GIT_CONFIG_NOSYSTEM: '1', GIT_CONFIG_GLOBAL: 'NUL', GIT_OPTIONAL_LOCKS: '0', GIT_TERMINAL_PROMPT: '0', SystemRoot: process.env.SystemRoot };
const run = (cwd, args, e = process.env) => { const r = spawnSync(gitExe, args, { cwd, encoding: 'utf8', env: e, windowsHide: true, timeout: 15000 }); return { s: r.status, o: (r.stdout||'').slice(0,600), e: (r.stderr||'').slice(0,400) }; };
const dir = mkdtempSync(join(tmpdir(), 'diag-')); const root = join(dir, 'repository'); mkdirSync(root);
run(root, ['init','--quiet']);
writeFileSync(join(root,'.gitignore'),'ignored.txt\n'); writeFileSync(join(root,'tracked.txt'),'original\n');
run(root, ['add','.']);
run(root, ['-c','user.name=S','-c','user.email=s@example.invalid','-c','commit.gpgsign=false','commit','--quiet','-m','f']);
const wt = join(dir,'linked-worktree');
const out = { wtAdd: run(root, ['worktree','add','--quiet','--detach',wt,'HEAD']) };
const st = ['--no-pager','-c','core.fsmonitor=false','-c','core.untrackedCache=false','status','--porcelain=v1','--untracked-files=normal','--ignore-submodules=none'];
out.statusProductEnv = run(wt, st, env);
out.statusInheritedEnv = run(wt, st);
out.statusRoot = run(root, st, env);
out.diff = run(wt, ['diff','--stat'], env);
out.eol = run(wt, ['ls-files','--eol'], env);
out.tmp = tmpdir();
console.log(JSON.stringify(out,null,2));
