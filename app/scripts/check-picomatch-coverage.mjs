import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { convert } from 'ast-v8-to-istanbul';
import { mergeProcessCovs } from '@bcoe/v8-coverage';
import { parseAstAsync } from 'vite';
import coverageLibrary from 'istanbul-lib-coverage';
import reportLibrary from 'istanbul-lib-report';
import reports from 'istanbul-reports';

const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const controller = path.join(app, 'scripts/picomatch-mitigation.mjs');
const directory = process.argv[2];
assert.ok(directory, 'Provide the NODE_V8_COVERAGE directory from a successful mitigation test run');
const equivalent = filename => process.platform === 'win32' ? filename.toLowerCase() : filename;
const captures = fs.readdirSync(directory).filter(name => name.endsWith('.json')).map(name => {
  const raw = JSON.parse(fs.readFileSync(path.join(directory, name), 'utf8'));
  return { result: raw.result.filter(script => script.url.startsWith('file:') && equivalent(fileURLToPath(script.url)) === equivalent(controller)) };
});
const merged = mergeProcessCovs(captures);
assert.equal(merged.result.length, 1, 'No unique real controller coverage was recorded');
const code = fs.readFileSync(controller, 'utf8');
const measured = await convert({ ast: parseAstAsync(code), code, wrapperLength: 0, coverage: merged.result[0] });
const map = coverageLibrary.createCoverageMap(measured);
assert.equal(map.files().length, 1);
const stats = map.fileCoverageFor(map.files()[0]).toSummary().toJSON();
assert.ok(stats.lines.covered > 0 && stats.lines.total > 0, 'Measured coverage is empty');
const output = path.join(app, 'coverage/picomatch-measured');
fs.mkdirSync(output, { recursive: true });
const context = reportLibrary.createContext({ dir: output, coverageMap: map });
reports.create('lcovonly', { projectRoot: path.join(app, '..') }).execute(context);
const native = fs.readFileSync(path.join(output, 'lcov.info'), 'utf8').replaceAll('\\', '/');
const target = 'app/scripts/picomatch-mitigation.mjs';
assert.equal(native.match(/^SF:(.+)$/m)?.[1], target);
const lcovPath = path.join(app, 'coverage/lcov.info');
const previous = fs.readFileSync(lcovPath, 'utf8');
const records = previous.split(/(?<=end_of_record\n)/);
const matching = records.map((record, index) => ({ index, file: record.match(/^SF:(.+)$/m)?.[1]?.replaceAll('\\', '/') })).filter(item => item.file === target);
assert.equal(matching.length, 1, 'Expected the existing controller record from Vitest, without excluding any source');
records[matching[0].index] = native;
fs.writeFileSync(lcovPath, records.join(''));
fs.writeFileSync(path.join(output, 'measured-summary.json'), JSON.stringify({ controller: target, captures: captures.filter(c => c.result.length).length, source: 'Real NODE_V8_COVERAGE from bounded integration tests; no synthetic hit counts or coverage exclusions.', stats }, null, 2) + '\n');
console.log(JSON.stringify({ controller: target, stats, otherLcovRecordsUnchanged: true }, null, 2));
